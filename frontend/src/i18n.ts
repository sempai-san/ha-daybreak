const languages: Record<string, Strings> = { en, de };

export function lang(hass?: HomeAssistant): string {
  const code = (hass?.locale?.language || hass?.language || navigator.language || "en").split("-")[0];
  return code in languages ? code : "en";
}

export function t(hass: HomeAssistant | undefined, key: StringKey, vars: Record<string, string | number> = {}): string {
  const text = languages[lang(hass)][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}

/** Readable message for a websocket error (known DayBreak codes are translated). */
export function errorText(hass: HomeAssistant | undefined, err: unknown): string {
  const e = err as { code?: string; message?: string } | undefined;
  const key = `err_${e?.code}` as StringKey;
  if (e?.code && key in en) return t(hass, key);
  return t(hass, "error", { msg: e?.message ?? String(err) });
}

/** Built-in profiles get their name in the user's language. */
const DEFAULT_PRESET_NAMES: Record<string, string> = { standard: "Standard", short: "Kurz", long: "Lang" };

export function localizeSnapshot<T extends { light_profiles: any[]; last_call_profiles: any[]; settings: any }>(
  hass: HomeAssistant | undefined,
  snapshot: T,
): T {
  const name = (p: { id: string; name: string; builtin?: boolean }) => {
    const key = `builtin_${p.id}` as StringKey;
    return p.builtin && key in en ? { ...p, name: t(hass, key) } : p;
  };
  const presets = (snapshot.settings?.snooze_presets ?? []).map((p: { id: string; name: string }) =>
    DEFAULT_PRESET_NAMES[p.id] === p.name ? { ...p, name: t(hass, `preset_${p.id}` as StringKey) } : p,
  );
  return {
    ...snapshot,
    settings: { ...snapshot.settings, snooze_presets: presets },
    light_profiles: snapshot.light_profiles.map(name),
    last_call_profiles: snapshot.last_call_profiles.map(name),
  };
}

// Short weekday names, Monday first (index 0 = Monday, like the backend).
export function weekdayNames(hass?: HomeAssistant): string[] {
  const fmt = new Intl.DateTimeFormat(locale(hass), { weekday: "short" });
  // 2024-01-01 was a Monday.
  return [...Array(7).keys()].map((i) => fmt.format(new Date(2024, 0, 1 + i)));
}

export function locale(hass?: HomeAssistant): string {
  return hass?.locale?.language || hass?.language || navigator.language || "en";
}
